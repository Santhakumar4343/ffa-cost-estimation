"""Generate theme tokens for light + dark mode.

Writes:
  src/theme.css            CSS custom properties (RGB channels) for :root (light) and .dark
  theme.colors.json        Tailwind colour map that references those variables

Theme-aware: neutrals (canvas/surface/line/ink/slate), the brand blue scale, and status tints.
Fixed in both themes: navy panels (logo navy), gold (logo star), orange accent (logo figure).
Run:  python scripts/gen-theme.py
"""

import json
from pathlib import Path


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, t):
    """t of colour a over colour b."""
    ra, rb = rgb(a), rgb(b)
    return "#%02x%02x%02x" % tuple(round(x * t + y * (1 - t)) for x, y in zip(ra, rb))


SURFACE_DARK = "#111a2e"

LIGHT = {
    "canvas": "#f4f6fa", "surface": "#ffffff", "line": "#e4e7ec", "line-soft": "#eef0f4",
    "ink": "#0b1220", "ink-2": "#344054", "ink-3": "#667085", "ink-4": "#98a2b3",
}
DARK = {
    "canvas": "#0a1020", "surface": SURFACE_DARK, "line": "#24324d", "line-soft": "#1b2740",
    "ink": "#e8edf6", "ink-2": "#c3cbdb", "ink-3": "#8f9bb2", "ink-4": "#66738c",
}

SLATE_L = {"50": "#f8fafc", "100": "#f1f5f9", "200": "#e2e8f0", "300": "#cbd5e1", "400": "#94a3b8"}
SLATE_D = {"50": "#162139", "100": "#1c2943", "200": "#263552", "300": "#34456a", "400": "#56668b"}

BRAND_L = {"50": "#eef4ff", "100": "#dbe7ff", "200": "#bdd3ff", "300": "#8fb3fb", "400": "#5287f2",
           "500": "#1f5fe0", "600": "#1349c0", "700": "#0d3d9c", "800": "#013876", "900": "#0a2a5c",
           "950": "#061a3d"}
BRAND_D = {"50": "#14244a", "100": "#1a2f5e", "200": "#24407a", "300": "#36589f", "400": "#5d8bf5",
           "500": "#3f74f0", "600": "#3366e6", "700": "#8fb3fb", "800": "#b6cdfd", "900": "#d6e3ff",
           "950": "#ebf1ff"}

# Tailwind default steps used by status tones.
STATUS = {
    "emerald": {"50": "#ecfdf5", "100": "#d1fae5", "200": "#a7f3d0", "300": "#6ee7b7", "400": "#34d399",
                "500": "#10b981", "600": "#059669", "700": "#047857", "800": "#065f46", "900": "#064e3b"},
    "amber": {"50": "#fffbeb", "100": "#fef3c7", "200": "#fde68a", "300": "#fcd34d", "400": "#fbbf24",
              "500": "#f59e0b", "600": "#d97706", "700": "#b45309", "800": "#92400e", "900": "#78350f"},
    "red": {"50": "#fef2f2", "100": "#fee2e2", "200": "#fecaca", "300": "#fca5a5", "400": "#f87171",
            "500": "#ef4444", "600": "#dc2626", "700": "#b91c1c", "800": "#991b1b", "900": "#7f1d1d"},
    "violet": {"50": "#f5f3ff", "100": "#ede9fe", "200": "#ddd6fe", "300": "#c4b5fd", "400": "#a78bfa",
               "500": "#8b5cf6", "600": "#7c3aed", "700": "#6d28d9", "800": "#5b21b6", "900": "#4c1d95"},
    "sky": {"50": "#f0f9ff", "100": "#e0f2fe", "200": "#bae6fd", "300": "#7dd3fc", "400": "#38bdf8",
            "500": "#0ea5e9", "600": "#0284c7", "700": "#0369a1", "800": "#075985", "900": "#0c4a6e"},
}


def status_dark(p):
    """Dark-mode mapping: tints become translucent-looking fills, text shades become light."""
    return {
        "50": mix(p["500"], SURFACE_DARK, 0.14), "100": mix(p["500"], SURFACE_DARK, 0.22),
        "200": mix(p["500"], SURFACE_DARK, 0.36), "300": p["300"], "400": p["400"], "500": p["500"],
        "600": p["400"], "700": p["300"], "800": p["200"], "900": p["100"],
    }


# Light tints of the fixed accents also adapt (used for icon chips / highlights).
GOLD_L = {"50": "#fffbea", "100": "#fff1c2"}
GOLD_D = {"50": mix("#fcbb0b", SURFACE_DARK, 0.14), "100": mix("#fcbb0b", SURFACE_DARK, 0.24)}
ACCENT_L = {"50": "#fff5e8", "100": "#ffe6c4"}
ACCENT_D = {"50": mix("#f98f03", SURFACE_DARK, 0.14), "100": mix("#f98f03", SURFACE_DARK, 0.24)}

light, dark = {}, {}
for k in LIGHT:
    light[k], dark[k] = LIGHT[k], DARK[k]
for name, L, Dk in (("slate", SLATE_L, SLATE_D), ("brand", BRAND_L, BRAND_D), ("gold", GOLD_L, GOLD_D),
                    ("accent", ACCENT_L, ACCENT_D)):
    for step in L:
        light[f"{name}-{step}"], dark[f"{name}-{step}"] = L[step], Dk[step]
for name, pal in STATUS.items():
    dpal = status_dark(pal)
    for step in pal:
        light[f"{name}-{step}"], dark[f"{name}-{step}"] = pal[step], dpal[step]


def block(sel, vals):
    lines = "\n".join(f"  --c-{k}: {' '.join(map(str, rgb(v)))};" for k, v in vals.items())
    return f"{sel} {{\n{lines}\n}}\n"


css = ("/* GENERATED by scripts/gen-theme.py — do not edit by hand. */\n"
       + block(":root,\n.theme-light,\n.dark .theme-light", light)
       + "\n" + block(".dark", dark))
root = Path(__file__).resolve().parent.parent
(root / "src" / "theme.css").write_text(css, encoding="utf-8")


def ref(k):
    return f"rgb(var(--c-{k}) / <alpha-value>)"


colors = {
    "canvas": ref("canvas"), "surface": ref("surface"),
    "line": {"DEFAULT": ref("line"), "soft": ref("line-soft")},
    "ink": {"DEFAULT": ref("ink"), "2": ref("ink-2"), "3": ref("ink-3"), "4": ref("ink-4")},
    "slate": {s: ref(f"slate-{s}") for s in SLATE_L},
    "brand": {s: ref(f"brand-{s}") for s in BRAND_L},
    **{n: {s: ref(f"{n}-{s}") for s in STATUS[n]} for n in STATUS},
    "gold_tints": {s: ref(f"gold-{s}") for s in GOLD_L},
    "accent_tints": {s: ref(f"accent-{s}") for s in ACCENT_L},
}
(root / "theme.colors.json").write_text(json.dumps(colors, indent=2), encoding="utf-8")
print(f"wrote {len(light)} tokens")
